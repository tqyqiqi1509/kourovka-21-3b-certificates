"""Strictly smaller COMPLETE cover family using small symmetric top merges.
See COVER_PRUNING.md. Imports the original generator for auditable comparison.
"""
from affine_covers import words_up_to,covers,prime_powers
from pathlib import Path
from math import prod
import argparse,json

def pruned_covers(n,words):
 idx={w:i for i,w in enumerate(words)}
 conflicts=[set() for w in words]
 for i,w in enumerate(words):
  for a in(2,3):
   if w+(a,) in idx:
    j=idx[w+(a,)];conflicts[i].add(j);conflicts[j].add(i)
 ans=[]
 for c in covers(n,words):
  sc=set(c)
  if all(not (conflicts[i]&sc) for i in c): ans.append(c)
 return ans

def export(B):
 dest=Path(__file__).resolve().parent;words=words_up_to(B)
 allcs={str(n):pruned_covers(n,words) for n in range(21,B+1)}
 obj={'max_degree':B,'pruning':'forbid simultaneous w and literal w+(2,) or w+(3,)',
      'word_convention':'bottom_to_top; AGL(d,p) for q=p^d; imprimitive action',
      'prime_powers':{str(q):list(pd) for q,pd in prime_powers(B).items()},
      'words':[list(w) for w in words],'word_degrees':[prod(w) for w in words],
      'covers_0based':allcs}
 (dest/f'affine_covers_pruned_through_{B}.json').write_text(json.dumps(obj))
 lines=['# Generated by affine_covers_pruned.py. See COVER_PRUNING.md for completeness proof.',
  'AffineWords := '+str([list(w) for w in words])+';',
  'AffineWordDegrees := '+str([prod(w) for w in words])+';',
  'AffineCoverDegrees := '+str(list(range(21,B+1)))+';',
  'AffineCovers := '+str([[[i+1 for i in c] for c in allcs[str(n)]] for n in range(21,B+1)])+';']
 (dest/f'affine_covers_pruned_through_{B}.g').write_text('\n'.join(lines)+'\n')
 print({n:len(allcs[str(n)]) for n in range(21,B+1)})
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--max-degree',type=int,default=40);args=ap.parse_args();export(args.max_degree)
