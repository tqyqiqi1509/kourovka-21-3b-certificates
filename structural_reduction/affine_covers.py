"""Complete finite overgroup family for soluble subgroups of S_n.

A word (q1,...,qr) denotes iterated imprimitive wreath product of
AGL(log_p(qi),p), where each qi is a prime power. Adjacent 2,2 are
excluded because C2 wr C2 <= S4 = AGL(2,2). A cover is a set of
DISTINCT words whose product-degrees sum to n. Empty word has degree1.
Repeated equal components can be enlarged to their wreath by C2,
therefore every soluble subgroup is contained in one cover.
The covers themselves need not be soluble.
"""
from pathlib import Path
from math import prod,isqrt
import argparse,json

def prime_powers(B):
 ans={}
 for p in range(2,B+1):
  if all(p%d for d in range(2,isqrt(p)+1)):
   q=p;d=1
   while q<=B:
    ans[q]=(p,d);q*=p;d+=1
 return ans

def words_up_to(B):
 pp=sorted(prime_powers(B))
 ans=[()]
 def rec(w,n):
  for q in pp:
   if n*q>B:break
   if w and w[-1]==q==2:continue
   nw=w+(q,);ans.append(nw);rec(nw,n*q)
 rec((),1)
 return sorted(ans,key=lambda w:(prod(w),w))

def covers(n,words=None):
 if words is None:words=words_up_to(n)
 deg=[prod(w) for w in words]
 def rec(i,left,acc):
  if left==0:
   yield list(acc);return
  while i<len(words) and deg[i]<=left:
   acc.append(i)
   yield from rec(i+1,left-deg[i],acc)
   acc.pop();i+=1
 return list(rec(0,n,[]))

def export(B):
 dest=Path(__file__).resolve().parent
 words=words_up_to(B)
 obj={'max_degree':B,'word_convention':'bottom_to_top; AGL(d,p) for q=p^d; imprimitive action',
      'prime_powers':{str(q):list(pd) for q,pd in prime_powers(B).items()},
      'words':[list(w) for w in words], 'word_degrees':[prod(w) for w in words],
      'covers_0based':{str(n):covers(n,words) for n in range(21,B+1)}}
 (dest/f'affine_covers_through_{B}.json').write_text(json.dumps(obj))
 # GAP indices are 1-based. All primitive parameters are positive integers.
 lines=['# Generated by affine_covers.py. Exact cover enumeration, not a result of testing.',
        'AffineWords := '+str([list(w) for w in words])+';',
        'AffineWordDegrees := '+str([prod(w) for w in words])+';',
        'AffineCoverDegrees := '+str(list(range(21,B+1)))+';',
        'AffineCovers := '+str([[[i+1 for i in c] for c in obj['covers_0based'][str(n)]] for n in range(21,B+1)])+';']
 (dest/f'affine_covers_through_{B}.g').write_text('\n'.join(lines)+'\n')
 print({n:len(obj['covers_0based'][str(n)]) for n in range(21,B+1)})
 print(dest/f'affine_covers_through_{B}.json')
 print(dest/f'affine_covers_through_{B}.g')
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--max-degree',type=int,default=24);args=ap.parse_args();export(args.max_degree)
